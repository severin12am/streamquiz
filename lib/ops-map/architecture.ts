export const MODULE_BY_ID: Record<string, OpsModule> = Object.fromEntries(
  OPS_MODULES.map((m) => [m.id, m]),
);

export const FLOW_BY_ID: Record<string, OpsFlow> = Object.fromEntries(
  OPS_FLOWS.map((f) => [f.id, f]),
);

export const ZONE_BY_ID: Record<string, OpsZone> = Object.fromEntries(
  OPS_ZONES.map((z) => [z.id, z]),
);

export function modulesInZone(zoneId: string): OpsModule[] {
  return OPS_MODULES.filter((m) => m.zoneId === zoneId);
}

export function flowsThroughModule(moduleId: string): OpsFlow[] {
  return OPS_FLOWS.filter((f) => f.hops.includes(moduleId));
}

export function uniqueFlowEdges(flows: OpsFlow[] = OPS_FLOWS): [string, string][] {
  const seen = new Set<string>();
  const edges: [string, string][] = [];
  for (const flow of flows) {
    for (let i = 0; i < flow.hops.length - 1; i++) {
      const a = flow.hops[i];
      const b = flow.hops[i + 1];
      const key = `${a}>${b}`;
      if (seen.has(key)) continue;
      seen.add(key);
      edges.push([a, b]);
    }
  }
  return edges;
}
